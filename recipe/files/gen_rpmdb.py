#!/usr/bin/env python3
"""gen_rpmdb.py <kubevirt-src> [--check] : write (or check) rpm/rpmdb/BUILD.bazel from KubeVirt's own lock
(rpm/BUILD.bazel rpmtree lists): the handler set is handlerbase_x86_64_cs9 plus the passt package whose passt-repair
binary the handler image carries; the launcher set is launcherbase_x86_64_cs9."""
import re, sys
src = sys.argv[1]
check = "--check" in sys.argv
EPOCH = "1791523273"
trees = {}
class Call:
    def __init__(self, kind): self.kind = kind
    def __call__(self, **kw):
        if self.kind == "rpmtree": trees[kw["name"]] = kw["rpms"]
env = {k: Call(k) for k in ("bazeldnf", "rpmtree", "tar2files", "centos_stream_alias")}
env.update(load=lambda *a, **k: None, centos_stream_config_settings=lambda *a, **k: None, select=lambda d, **k: d)
exec(compile(open(f"{src}/rpm/BUILD.bazel").read(), "rpm/BUILD.bazel", "exec"), env)
passt = [r for r in trees["passt_tree_x86_64_cs9"] if re.match(r"@passt-\d", r)]
assert len(passt) == 1, passt
sets = {"handler_x86_64_cs9": sorted(set(trees["handlerbase_x86_64_cs9"] + passt)),
        "launcher_x86_64_cs9": sorted(set(trees["launcherbase_x86_64_cs9"]))}
out = ['# ReadyStack: RPM databases for the virt-handler and virt-launcher images, generated by gen_rpmdb.py from',
       '# rpm/BUILD.bazel (KubeVirt\'s own lock). Do not edit by hand.', '',
       'load(":rpmdb.bzl", "rpmdb")', '']
for name, rpms in sets.items():
    out += ['rpmdb(', f'    name = "{name}",', '    rpms = [']
    out += [f'        "{r}",' for r in rpms]
    out += ['    ],', f'    source_date_epoch = "{EPOCH}",', '    visibility = ["//visibility:public"],', ')', '']
text = "\n".join(out)
path = f"{src}/rpm/rpmdb/BUILD.bazel"
if check:
    cur = open(path).read()
    sys.exit(0 if cur == text else "rpm/rpmdb/BUILD.bazel is stale against rpm/BUILD.bazel")
import os; os.makedirs(os.path.dirname(path), exist_ok=True); open(path, "w").write(text)
print({k: len(v) for k, v in sets.items()})
